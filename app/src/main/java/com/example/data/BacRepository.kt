    // Helper functions for search
    fun searchTerms(query: String): List<TermItem> {
        if (query.isBlank()) return termsList
        return termsList.filter {
            it.term.contains(query, ignoreCase = true) ||
                it.definition.contains(query, ignoreCase = true) ||
                it.unit.contains(query, ignoreCase = true)
        }
    }

    fun searchFigures(query: String): List<FigureItem> {
        if (query.isBlank()) return figuresList
        return figuresList.filter {
            it.name.contains(query, ignoreCase = true) ||
                it.roleTitle.contains(query, ignoreCase = true) ||
                it.nationality.contains(query, ignoreCase = true) ||
                it.biography.contains(query, ignoreCase = true)
        }
    }

